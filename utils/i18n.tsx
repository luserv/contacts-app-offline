export type T = typeof translations.es;

interface I18nContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: T;
}

const I18nContext = createContext<I18nContextType>({
  lang: 'es',
  setLang: () => {},
  t: translations.es,
});

function detectDeviceLang(): Lang {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale;
    return locale.startsWith('es') ? 'es' : 'en';
  } catch {
    return 'es';
  }
}

/** For code outside React (notifications): same language resolution as I18nProvider. */
export async function getTranslations(): Promise<T> {
  try {
    const stored = await storage.getItem(LANG_KEY);
    if (stored === 'es' || stored === 'en') return translations[stored] as T;
  } catch {}
  return translations[detectDeviceLang()] as T;
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('es');

  useEffect(() => {
    storage.getItem(LANG_KEY).then(stored => {
      if (stored === 'es' || stored === 'en') {
        setLangState(stored);
      } else {
        setLangState(detectDeviceLang());
      }
    });
  }, []);

  const setLang = async (newLang: Lang) => {
    setLangState(newLang);
    await storage.setItem(LANG_KEY, newLang);
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t: translations[lang] as T }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
